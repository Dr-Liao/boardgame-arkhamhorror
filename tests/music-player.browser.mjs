import { test, expect } from '@playwright/test'
import { mkdirSync } from 'node:fs'

test('音乐播放器持续播放、切歌、进度、音量保存、退出暂停与窄屏', async ({ page, request }) => {
  const errors = []; page.on('pageerror', e => errors.push(e.message))
  await page.addInitScript(() => {
    const NativeAudio = window.Audio
    window.__musicAudio = []
    window.Audio = function (...args) { const audio = new NativeAudio(...args); window.__musicAudio.push(audio); return audio }
    window.Audio.prototype = NativeAudio.prototype
  })
  await page.route('**/api/start', async route => {
    const response = await route.fetch({ postData: JSON.stringify({ modId: 'arkhamhorror', settings: { legacyAutoStart: true, playerCount: 1, playerInvestigator: '01001', seed: 'music-player' } }) })
    await route.fulfill({ response })
  })
  await page.setViewportSize({ width: 1920, height: 1080 })
  await page.goto('/index.html')
  await page.locator('.bg-card').filter({ hasText: '诡镇奇谈' }).click()
  await page.getByRole('button', { name: '开始新游戏' }).click()
  await page.getByRole('button', { name: '跳过演出' }).click()
  const dock = page.locator('.ah-music')
  await expect(dock).toBeVisible()
  await dock.getByRole('button', { name: '展开音乐播放器', exact: true }).click()
  const player = page.getByRole('region', { name: '音乐播放器' })
  await expect(player).toBeVisible()
  await expect(player.locator('.ah-music-track')).toHaveCount(3)
  await expect(player.getByRole('button', { name: '暂停音乐', exact: true })).toBeVisible()
  const transport = expression => page.evaluate(expression)
  await expect.poll(() => transport(() => window.__musicAudio.find(a => a.src.includes('/music/'))?.currentTime || 0)).toBeGreaterThan(.1)
  await expect.poll(() => transport(() => window.__musicAudio.find(a => a.src.includes('/music/'))?.duration || 0)).toBeGreaterThan(200)
  await page.getByRole('button', { name: '刷新局势' }).click()
  await expect(player).toBeVisible()
  expect(await transport(() => window.__musicAudio.filter(a => a.src.includes('/music/')).length)).toBe(1)
  await player.getByRole('slider', { name: '音乐进度' }).fill('25')
  await expect.poll(() => transport(() => window.__musicAudio.find(a => a.src.includes('/music/')).currentTime)).toBeGreaterThan(50)
  await player.getByRole('slider', { name: '音乐音量' }).fill('18')
  expect(await transport(() => window.__musicAudio.find(a => a.src.includes('/music/')).volume)).toBe(.18)
  await player.getByRole('button', { name: '静音音乐', exact: true }).click()
  expect(await transport(() => window.__musicAudio.find(a => a.src.includes('/music/')).muted)).toBe(true)
  await player.getByRole('button', { name: '取消音乐静音' }).click()
  await player.getByRole('button', { name: '下一首' }).click()
  await expect(player.locator('.ah-music-now')).toHaveText('Long note One')
  await expect.poll(() => transport(() => window.__musicAudio.find(a => a.src.includes('/music/')).currentTime)).toBeGreaterThan(.1)
  await transport(() => window.__musicAudio.find(a => a.src.includes('/music/')).dispatchEvent(new Event('ended')))
  await expect(player.locator('.ah-music-now')).toHaveText('The Dread')
  await expect.poll(() => transport(() => window.__musicAudio.find(a => a.src.includes('/music/')).currentTime)).toBeGreaterThan(.1)
  await player.getByRole('button', { name: '列表循环', exact: true }).click()
  expect(await transport(() => window.__musicAudio.find(a => a.src.includes('/music/')).loop)).toBe(true)
  mkdirSync('artifacts/arkham-polish', { recursive: true })
  await page.screenshot({ path: 'artifacts/arkham-polish/music-player-final.png', animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(player).toBeInViewport()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await player.getByRole('button', { name: '暂停音乐', exact: true }).click()
  expect(await transport(() => window.__musicAudio.find(a => a.src.includes('/music/')).paused)).toBe(true)
  await page.getByRole('button', { name: '刷新局势' }).click()
  expect(await transport(() => window.__musicAudio.find(a => a.src.includes('/music/')).paused)).toBe(true)
  await page.reload()
  await page.getByRole('button', { name: '跳过演出' }).click()
  await dock.getByRole('button', { name: '展开音乐播放器', exact: true }).click()
  await expect(player.locator('.ah-music-now')).toHaveText('The Dread')
  await expect(player.getByRole('slider', { name: '音乐音量' })).toHaveValue('18')
  await expect(player.getByRole('button', { name: '单曲循环', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(player.getByRole('button', { name: '暂停音乐', exact: true })).toBeVisible()
  await expect.poll(() => transport(() => window.__musicAudio.find(a => a.src.includes('/music/'))?.currentTime || 0)).toBeGreaterThan(.1)
  await page.setViewportSize({ width: 1920, height: 1080 })
  await page.locator('.ah-session-menu summary').click()
  await page.getByRole('button', { name: '退出', exact: true }).click()
  await expect(dock).toHaveCount(0)
  expect(await transport(() => window.__musicAudio.every(a => a.paused))).toBe(true)

  // Campaign preparation stays silent; entering the scenario enables music.
  await page.unroute('**/api/start')
  await page.locator('.bg-card').filter({ hasText: '诡镇奇谈' }).click()
  await page.getByRole('button', { name: '开始新游戏' }).click()
  await expect(page.locator('.ah-hub')).toBeVisible()
  await expect(dock).toHaveCount(0)
  expect(await transport(() => window.__musicAudio.every(a => a.paused))).toBe(true)
  await page.getByRole('button', { name: '选择调查员', exact: true }).click()
  await page.getByRole('button', { name: /选择调查员：罗兰/ }).first().click()
  await page.getByRole('button', { name: /自动构筑/ }).first().click()
  await page.getByRole('button', { name: '确认准备', exact: true }).first().click()
  await page.getByRole('button', { name: '开始当前关卡' }).first().click()
  await expect(page.locator('.ah-table')).toBeVisible()
  await page.getByRole('button', { name: '跳过演出' }).click()
  await expect(dock).toBeVisible()
  await dock.getByRole('button', { name: '展开音乐播放器', exact: true }).click()
  await expect(player.getByRole('button', { name: '暂停音乐', exact: true })).toBeVisible()
  await expect.poll(() => transport(() => window.__musicAudio.find(a => a.src.includes('/music/')).paused)).toBe(false)
  await page.route('**/audio/music/common/darkest-child.mp3', route => route.abort())
  await player.getByRole('button', { name: '播放 Darkest Child', exact: true }).click()
  await expect(player.locator('.ah-music-feedback')).toContainText(/失败|无法播放/)
  await page.unroute('**/audio/music/common/darkest-child.mp3')
  await player.getByRole('button', { name: '播放音乐', exact: true }).click()
  await expect.poll(() => transport(() => window.__musicAudio.find(a => a.src.includes('/music/')).currentTime)).toBeGreaterThan(.1)

  // Every added file must decode and play, not just return a successful HTTP response.
  for (const title of ['Darkest Child', 'Long note One', 'The Dread']) {
    await player.getByRole('button', { name: '播放 ' + title, exact: true }).click()
    await expect(player.locator('.ah-music-now')).toHaveText(title)
    await expect.poll(() => transport(() => window.__musicAudio.find(a => a.src.includes('/music/')).duration || 0)).toBeGreaterThan(60)
    await expect.poll(() => transport(() => window.__musicAudio.find(a => a.src.includes('/music/')).currentTime)).toBeGreaterThan(.1)
  }

  const url = '/mods/arkhamhorror/audio/music/common/darkest-child.mp3'
  const partial = await request.get(url, { headers: { Range: 'bytes=10-19' } })
  expect(partial.status()).toBe(206); expect(partial.headers()['content-type']).toBe('audio/mpeg')
  expect((await partial.body()).length).toBe(10)
  const suffix = await request.get(url, { headers: { Range: 'bytes=-10' } })
  expect(suffix.status()).toBe(206); expect((await suffix.body()).length).toBe(10)
  const invalid = await request.get(url, { headers: { Range: 'bytes=999999999-' } })
  expect(invalid.status()).toBe(416)
  const stale = await request.get(url, { headers: { Range: 'bytes=10-19', 'If-Range': '"old"' } })
  expect(stale.status()).toBe(200)
  expect(errors).toEqual([])
})
