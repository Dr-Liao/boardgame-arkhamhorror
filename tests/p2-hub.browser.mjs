test('P2 局外面板建档、构筑、显式读档与删除确认', async ({ page }) => {
  await page.goto('/index.html')
  await page.locator('.bg-card').filter({ hasText: '诡镇奇谈' }).click()
  const setup = page.locator('.ah-hub-setup')
  await expect(setup).toBeVisible()
  await expect(setup.locator('.bg-field')).toHaveCount(3)
  await setup.getByText(/玩家人数|席位数量/).locator('..').locator('select').selectOption('1')
  await expect(setup.locator('.bg-field')).toHaveCount(2)
  const created = page.waitForResponse('**/api/start')
  await setup.getByRole('button', { name: '开始新游戏' }).click()
  const createdResult = await created
  expect(createdResult.status()).toBe(200)
  const sessionId = (await createdResult.json()).session.sessionId
  const hub = page.locator('.ah-hub')
  await expect(hub).toHaveAttribute('data-ui-state', 'campaignHub')
  const navigation = hub.getByRole('navigation', { name: '战役局外页面' })
  await expect(navigation.getByRole('button')).toHaveCount(8)
  await expect(navigation.getByRole('button').first()).toHaveAccessibleName('开始关卡')
  await navigation.getByRole('button', { name: '开始关卡', exact: true }).click()
  await expect(hub.getByRole('button', { name: '开始当前关卡' })).toBeDisabled()
  await hub.getByRole('button', { name: '关卡选择' }).click()
  await expect(hub).toContainText('第一幕：集结')
  await hub.getByRole('button', { name: '战役总览' }).click()
  await hub.getByRole('button', { name: '选择调查员', exact: true }).click()
  await expect(hub).toHaveAttribute('data-ui-state', 'scenarioSetup')
  await hub.getByRole('button', { name: /选择调查员：罗兰/ }).first().click()
  await hub.getByRole('button', { name: /自动构筑/ }).first().click()
  await navigation.getByRole('button', { name: '开始关卡', exact: true }).click()
  await expect(hub.getByRole('button', { name: '开始当前关卡' })).toBeDisabled()
  await expect(hub.locator('.ah-departure-checks .is-done')).toHaveCount(2)
  await navigation.getByRole('button', { name: '调查员与席位', exact: true }).click()
  await hub.getByRole('button', { name: '确认准备', exact: true }).first().click()
  await expect(hub).toContainText('牌组')
  await expect(hub.getByRole('button', { name: '开始当前关卡' }).first()).toBeVisible()
  await expect(navigation.getByRole('button', { name: '开始关卡', exact: true })).toHaveAttribute('aria-current', 'page')
  await expect(hub.getByRole('button', { name: '开始当前关卡' })).toBeEnabled()
  for (const tab of ['战役总览', '关卡选择', '调查员与席位', '卡组构筑']) {
    await navigation.getByRole('button', { name: tab, exact: true }).click()
    await expect(hub.getByRole('button', { name: '开始当前关卡' })).toHaveCount(0)
  }
  await hub.getByRole('button', { name: '退出' }).click()
  await expect(page.locator('.bg-card').filter({ hasText: '诡镇奇谈' })).toBeVisible()

  await page.reload()
  await page.locator('.bg-card').filter({ hasText: '诡镇奇谈' }).click()
  await setup.getByRole('button', { name: '存档管理' }).click()
  const save = setup.locator(`.ah-save-item[data-session-id="${sessionId}"]`)
  await expect(save).toContainText('调查准备')
  await expect(save.getByRole('button', { name: '读取此存档' })).toBeEnabled()
  await save.getByRole('button', { name: '读取此存档' }).click()
  await expect(hub).toHaveAttribute('data-ui-state', 'scenarioSetup')
  await hub.getByRole('button', { name: '退出' }).click()
  await page.locator('.bg-card').filter({ hasText: '诡镇奇谈' }).click()
  await setup.getByRole('button', { name: '存档管理' }).click()
  await expect(setup.locator('.ah-save-item').first()).toBeVisible()
  const count = await setup.locator('.ah-save-item').count()
  await save.getByRole('button', { name: '删除', exact: true }).click()
  await expect(setup.locator('.ah-save-item')).toHaveCount(count)
  await save.getByRole('button', { name: '确认删除此存档' }).click()
  await expect(setup.locator('.ah-save-item')).toHaveCount(count - 1)
})

test('P2 结算、升级与下一关在局外页面串联', async ({ page, request }) => {
  await page.goto('/index.html')
  await page.locator('.bg-card').filter({ hasText: '诡镇奇谈' }).click()
  const setup = page.locator('.ah-hub-setup')
  await setup.getByText(/玩家人数|席位数量/).locator('..').locator('select').selectOption('1')
  const startedResponse = page.waitForResponse('**/api/start')
  await setup.getByRole('button', { name: '开始新游戏' }).click()
  let session = (await (await startedResponse).json()).session
  const hub = page.locator('.ah-hub')
  await hub.getByRole('button', { name: '选择调查员', exact: true }).click()
  await hub.getByRole('button', { name: /选择调查员：罗兰/ }).first().click()
  await hub.getByRole('button', { name: /自动构筑/ }).first().click()
  await hub.getByRole('button', { name: '确认准备', exact: true }).first().click()
  await hub.getByRole('button', { name: '开始当前关卡' }).first().click()
  await expect(page.locator('.bg-game:not(.ah-hub)')).toBeVisible()
  const current = await request.get(`/api/session?sessionId=${encodeURIComponent(session.sessionId)}`)
  session = (await current.json()).session
  for (let i = 0; session.state.uiState !== 'scenarioResult'; i++) {
    expect(i).toBeLessThan(150)
    const moves = session.state.legalMoves
    const move = session.state.pendingChoice
      ? moves.find(item => ['done', 'skip', 'self'].includes(item.optionId)) || moves[0]
      : moves.find(item => item.action === 'endTurn')
    expect(move).toBeTruthy()
    const response = await request.post('/api/move', { data: { sessionId: session.sessionId, revision: session.state.revision,
      move: { ...move, revision: session.state.revision } } })
    expect(response.ok()).toBe(true)
    session = (await response.json()).session
  }
  await page.reload()
  await page.locator('.bg-card').filter({ hasText: '诡镇奇谈' }).click()
  await setup.getByRole('button', { name: '存档管理' }).click()
  const save = setup.locator(`.ah-save-item[data-session-id="${session.sessionId}"]`)
  await expect(save).toBeVisible()
  await save.getByRole('button', { name: '读取此存档' }).click()
  await expect(hub).toHaveAttribute('data-ui-state', 'scenarioResult')
  await expect(hub).toContainText('本关结算')
  const actual = session.state.campaignStory.entries.find(e=>e.kind==='result')
  for (const paragraph of actual.paragraphs) await expect(hub.locator('.ah-story-page')).toContainText(paragraph)
  await expect(hub.locator('.ah-story-consequences')).toBeVisible()
  await page.screenshot({ path: fileURLToPath(new URL('../../../artifacts/arkham-polish/hub-result.png', import.meta.url)), animations: 'disabled' })
  await hub.getByRole('button', { name: /继续|进入关间/ }).first().click()
  await expect(hub).toHaveAttribute('data-ui-state', 'interlude')
  await expect(hub.locator('.ah-office-upgrade-gallery img').first()).toBeVisible()
  await expect(hub.locator('.ah-upgrade-card-description')).toHaveCount(2)
  await expect(hub.locator('.ah-upgrade-card-description').last()).not.toBeEmpty()
  await page.evaluate(async () => Promise.all([...document.images].map(img => img.decode().catch(() => {}))))
  await page.screenshot({ path: fileURLToPath(new URL('../../../artifacts/arkham-polish/hub-upgrade.png', import.meta.url)), animations: 'disabled' })
  expect(await hub.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true)
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await hub.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true)
  await page.screenshot({ path: fileURLToPath(new URL('../../../artifacts/arkham-polish/hub-upgrade-mobile.png', import.meta.url)), animations: 'disabled' })
  await page.setViewportSize({ width: 1400, height: 950 })
  const purchase = hub.getByRole('button', { name: /加入升级方案/ })
  if (await purchase.count()) {
    await purchase.click()
    await expect(hub.locator('.ah-upgrade-preview')).toBeVisible()
    await hub.getByRole('button', { name: '保存升级方案', exact: true }).first().click()
  }
  await hub.getByRole('button', { name: /准备下一关/, exact: false }).first().click()
  await expect(hub).toHaveAttribute('data-ui-state', 'scenarioSetup')
  await hub.getByRole('button', { name: '开始当前关卡' }).first().click()
  await expect(page.locator('.bg-game:not(.ah-hub)')).toBeVisible()
  const next = await request.get(`/api/session?sessionId=${encodeURIComponent(session.sessionId)}`)
  expect((await next.json()).session.state.scenario.id).toBe('theMidnightMasks')
})


