const GAP_NOTE = /（[^）]*gaps[^）]*）/g

export function scenarioGuide(id) {
  return GUIDES[id] || null
}

// 玩家看到的设置文本：优先用上面补写的 setup，否则用场景自带的摘要，并去掉开发备注。
export function scenarioSetupText(scenario) {
  const guide = scenarioGuide(scenario?.id)
  const raw = guide?.setup || scenario?.setup || ''
  return String(raw).replace(GAP_NOTE, '').replace(/[ \t]{2,}/g, ' ').trim()
}
