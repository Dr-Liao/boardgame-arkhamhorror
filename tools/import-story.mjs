// Import complete narrative paragraphs from the bundled translation. Setup and
// branch-routing instructions are deliberately excluded from the reader.
import { readFileSync, writeFileSync } from 'node:fs'
const source = new URL('../../../参考资源/ArkhamHorror-main/frontend/src/locales/zh/nightOfTheZealot/', import.meta.url)
const read = file => JSON.parse(readFileSync(new URL(file, source), 'utf8'))
export function paragraphs(html) {
  return [...html.matchAll(/<p\b([^>]*)>([\s\S]*?)<\/p>/g)]
    .filter(([, attrs]) => !/\bbasic\b/.test(attrs))
    .map(([, , text]) => text.replace(/<[^>]*>/g, '')
      .replace(/^_(?:引言|结局)\s*\d+_[:：]\s*/, '')
      .replace(/^_如果未达成任何结局[^_]*_[:：]\s*/, '')
      .replace(/在剧本日志中记录\s*\*[^*]+\*。?$/, '')
      .replace(/。\./g, '。').trim())
}
const gathering = read('scenarios/theGathering.json'), masks = read('scenarios/theMidnightMasks.json'), devourer = read('scenarios/theDevourerBelow.json')
function resolutions(scenario) {
  return Object.fromEntries(Object.entries(scenario.resolutions).flatMap(([key, value]) => {
    if (!/^(noResolution|resolution\d+)$/.test(key)) return []
    const body = typeof value === 'string' ? value : value.body
    const prose = paragraphs(body || '')
    return prose.length ? [[key.replace(/^resolution/, 'r'), prose]] : []
  }))
}
const data = {
  prologue: { title: '食尸鬼们早已饥肠辘辘……', paragraphs: paragraphs(read('base.json').prologue) },
  theGathering: paragraphs(gathering.intro.body),
  theMidnightMasks: { others: paragraphs(masks.intro1), survivors: paragraphs(masks.intro2), common: paragraphs(masks.intro3) },
  theDevourerBelow: paragraphs(devourer.intro.body),
  resolutions: {
    theGathering: resolutions(gathering),
    theMidnightMasks: resolutions(masks),
    theDevourerBelow: resolutions(devourer),
  },
}
const output = new URL('../content/campaigns/nightOfTheZealot/story-text.js', import.meta.url)
const text = '// Generated by tools/import-story.mjs from bundled zh/nightOfTheZealot translations.\n// Narrative only; select the reached branch before projecting to players.\nexport const STORY_TEXT = ' + JSON.stringify(data, null, 2) + '\n'
if (process.argv.includes('--write')) writeFileSync(output, text)
else if (readFileSync(output, 'utf8') !== text) throw new Error('Story text is out of date; run import-story.mjs --write')
console.log('Complete introduction and resolution paragraphs verified.')
