import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { manifest } from '../content/packs/carcosaPlayer/manifest.js'
import { ALL_CARDS } from '../src/cards/cards-data.js'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..')
const game = 'games/arkhamhorror'
const files = [`${game}/tests/carcosa-player-acceptance.test.mjs`]
const implementationFiles = [
  `${game}/content/packs/carcosaPlayer/effects.js`,
  `${game}/content/packs/carcosaPlayer/manifest.js`,
  `${game}/src/deck/availability.js`,
  `${game}/src/engine/effects.js`,
  `${game}/src/engine/engine.js`,
]
const hash = bytes => createHash('sha256').update(bytes).digest('hex')
const home = path.join(root, 'artifacts/carcosa-migration/audit-home')
fs.mkdirSync(home, { recursive: true })

const run = spawnSync(process.execPath, [
  '--test',
  `--test-reporter=./${game}/tools/core-test-reporter.mjs`,
  ...files,
], {
  cwd: root,
  env: { ...process.env, DSH_HOME: home },
  encoding: 'utf8',
  maxBuffer: 32 * 1024 * 1024,
})
const results = run.stdout.trim().split('\n').filter(Boolean).map(line => JSON.parse(line))
fs.writeFileSync(path.join(root, 'artifacts/carcosa-migration/player-acceptance-results.json'),
  `${JSON.stringify(results, null, 2)}\n`)
if (run.status !== 0 || !results.length || results.some(result =>
  result.type !== 'test:pass' || result.skipped || result.todo)) {
  console.error(results.filter(result =>
    result.type !== 'test:pass' || result.skipped || result.todo), run.stderr)
  process.exit(1)
}

const cards = manifest.cards.map(entry => ALL_CARDS[entry.code]).sort((left, right) => left.code.localeCompare(right.code))
if (cards.length !== 95) throw new Error(`Unexpected Carcosa player scope: ${cards.length}`)
const passed = new Map(results.map(result => [result.name, result]))
const entries = cards.map(card => {
  const titles = results.filter(result => new RegExp(`^Carcosa ${card.code}\\b`).test(result.name)).map(result => result.name)
  if (!titles.length) throw new Error(`No per-card behavioral evidence: ${card.code} ${card.name}`)
  if (titles.every(title => /目录|存在|可构筑|处理器/.test(title))) {
    throw new Error(`Catalog-only proof is insufficient: ${card.code}`)
  }
  return {
    code: card.code,
    name: card.nameZh || card.name,
    type: card.type,
    class: card.klass,
    level: card.xp || 0,
    basicWeakness: manifest.basicWeaknessCodes.includes(card.code),
    status: 'verified',
    evidence: titles.map(title => {
      const result = passed.get(title)
      return { file: path.relative(root, result.file).replaceAll('\\', '/'), test: title }
    }),
  }
})

const profile = {
  id: 'original-carcosa-player-cycle-2026-10',
  scope: '卡尔克萨之路原始循环玩家包95张：92张构筑卡与3张基础弱点。',
  basis: '原始印刷卡文、后端参考实现及所列逐卡回归测试；验收主要印刷效果和列明边界，不声称穷举所有跨循环组合。',
  houseRules: [
    '沿用项目现有的自动奖励反应、协作请求及确定性选择事务',
    '卡牌随机、搜索和选择必须通过统一存档回放路径',
    '升级卡仅进入升级池；基础弱点只进入随机基础弱点池',
  ],
  sources: [
    '参考资源/ArkhamHorror-main/frontend/public/cards_en.json',
    '参考资源/ArkhamHorror-main/backend/arkham-api/library/Arkham',
  ],
}
const ledger = {
  schemaVersion: 1,
  profile,
  summary: {
    total: entries.length,
    constructible: entries.filter(entry => !entry.basicWeakness).length,
    basicWeaknesses: entries.filter(entry => entry.basicWeakness).length,
    verified: entries.length,
    unverified: 0,
    testsPassed: results.length,
  },
  testFiles: files.map(file => ({ file, sha256: hash(fs.readFileSync(path.join(root, file))) })),
  implementationFiles: implementationFiles.map(file =>
    ({ file, sha256: hash(fs.readFileSync(path.join(root, file))) })),
  entries,
}
const json = `${JSON.stringify(ledger, null, 2)}\n`
const module = `// Generated by tools/audit-carcosa-player.mjs after executing C2 behavioral tests.
// Detailed evidence: audit/carcosa-player-acceptance.json.
export const CARCOSA_PLAYER_ACCEPTANCE_PROFILE = ${JSON.stringify(profile, null, 2)}
export const CARCOSA_PLAYER_ACCEPTANCE_SHA256 = '${hash(json)}'
const verified = new Set(${JSON.stringify(entries.map(entry => entry.code))})
export const carcosaPlayerCardVerified = code => verified.has(code)
`
for (const [file, text] of [
  ['audit/carcosa-player-acceptance.json', json],
  ['src/cards/carcosa-player-acceptance.js', module],
]) {
  const destination = path.join(root, game, file)
  if (process.argv.includes('--write')) fs.writeFileSync(destination, text)
  else if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== text) {
    throw new Error(`Acceptance artifact stale: ${file}`)
  }
}
console.log(JSON.stringify(ledger.summary))
