import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { ALL_CARDS } from '../src/cards/cards-data.js'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..')
const game = 'games/arkhamhorror'
const cyclePacks = new Set(['dwl', 'tmm', 'tece', 'bota', 'uau', 'wda', 'litas'])
const files = [
  `${game}/tests/dunwich-player-acceptance.test.mjs`,
  `${game}/tests/dunwich-encounter-acceptance.test.mjs`,
  `${game}/tests/dunwich-scenario-acceptance.test.mjs`,
]
const hash = bytes => createHash('sha256').update(bytes).digest('hex')
const home = path.join(root, 'artifacts/dunwich-acceptance/audit-home')
fs.mkdirSync(home, { recursive: true })

const run = spawnSync(process.execPath, [
  '--test',
  `--test-reporter=./${game}/tools/core-test-reporter.mjs`,
  ...files,
], {
  cwd: root,
  env: { ...process.env, DSH_HOME: home },
  encoding: 'utf8',
  maxBuffer: 64 * 1024 * 1024,
})
const results = run.stdout.trim().split('\n').filter(Boolean).map(line => JSON.parse(line))
fs.writeFileSync(
  path.join(root, 'artifacts/dunwich-acceptance/acceptance-results.json'),
  `${JSON.stringify(results, null, 2)}\n`,
)
if (run.status !== 0 || !results.length || results.some(result =>
  result.type !== 'test:pass' || result.skipped || result.todo)) {
  console.error(results.filter(result =>
    result.type !== 'test:pass' || result.skipped || result.todo), run.stderr)
  process.exit(1)
}

const cards = Object.values(ALL_CARDS)
  .filter(card => cyclePacks.has(card.pack))
  .sort((left, right) => left.code.localeCompare(right.code))
if (cards.length !== 333) throw new Error(`Unexpected Dunwich scope: ${cards.length}`)

const passed = new Map(results.map(result => [result.name, result]))
const entries = cards.map(card => {
  const titles = results
    .filter(result => new RegExp(`^Dunwich ${card.code}\\b`).test(result.name))
    .map(result => result.name)
  if (!titles.length) throw new Error(`No behavioral evidence: ${card.code} ${card.name}`)
  if (titles.every(title => /目录|存在|可构筑|处理器/.test(title))) {
    throw new Error(`Catalog-only proof is insufficient: ${card.code}`)
  }
  return {
    code: card.code,
    name: card.nameZh || card.name,
    type: card.type,
    status: 'verified',
    evidence: [...new Set(titles)].sort().map(title => {
      const result = passed.get(title)
      return { file: path.relative(root, result.file).replaceAll('\\', '/'), test: title }
    }),
  }
})

const profile = {
  id: 'original-dunwich-cycle-2026-10',
  scope: '敦威治遗产周期七个原始卡包共333条目录记录，包含玩家卡、调查员、弱点、遭遇卡、剧情支援及八章结构卡。',
  basis: '原始印刷卡文、战役规则及所列逐卡回归测试；逐卡主要效果和已列边界通过，未声称穷举所有卡牌组合。',
  houseRules: [
    '保留项目既有的自动奖励反应与协作请求规则',
    '结构卡以印刷正反面、确定性布置、区域守恒及对应章节行为共同验收',
    '存档与重放沿用引擎统一事务模型',
  ],
  sources: [
    '参考资源/ArkhamHorror-main/frontend/public/cards_en.json',
    '参考资源/ArkhamHorror-main/backend/arkham-api/library/Arkham',
  ],
}
const ledger = {
  schemaVersion: 1,
  profile,
  summary: {
    total: entries.length,
    verified: entries.length,
    unverified: 0,
    unimplemented: 0,
    testsPassed: results.length,
  },
  testFiles: files.map(file => ({
    file,
    sha256: hash(fs.readFileSync(path.join(root, file))),
  })),
  entries,
}
const json = `${JSON.stringify(ledger, null, 2)}\n`
const module = `// Generated by tools/audit-dunwich-acceptance.mjs after executing behavioral tests.
// Detailed evidence: audit/dunwich-acceptance.json. Not a promise of all-combination equivalence.
export const DUNWICH_ACCEPTANCE_PROFILE = ${JSON.stringify(profile, null, 2)}
export const DUNWICH_ACCEPTANCE_SHA256 = '${hash(json)}'
const verified = new Set(${JSON.stringify(entries.map(entry => entry.code))})
export const dunwichCardVerified = code => verified.has(code)
`
for (const [file, text] of [
  ['audit/dunwich-acceptance.json', json],
  ['src/cards/dunwich-acceptance.js', module],
]) {
  const destination = path.join(root, game, file)
  if (process.argv.includes('--write')) fs.writeFileSync(destination, text)
  else if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== text) {
    throw new Error(`Acceptance artifact stale: ${file}`)
  }
}
console.log(JSON.stringify(ledger.summary))
