  '01075':['N4.2 幸运兔脚在任意技能检定失败后触发，不只限于调查/攻击/躲避入口'],
  '01117':['N4 幕二丽塔无人控制，谈判成功转移同一实例而非生成副本','N3 同次伤害恐惧可分配给同一资产，全部分配后才弃置'],
