import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'
import { MOD, REFERENCE, sourceLock, sha, json } from './tic-migration-lib.mjs'
import { chapters } from '../content/campaigns/theInnsmouthConspiracy/shared.js'
const sourceRoot = join(REFERENCE, 'frontend/src/locales')
const supplementPath = 'content/campaigns/theInnsmouthConspiracy/story-source/translations.json'
const output = 'content/campaigns/theInnsmouthConspiracy/story-text.js'
const files = ['base.json', ...chapters.map(ch => `scenarios/${ch.id}.json`)]
const supplement = JSON.parse(readFileSync(join(MOD, supplementPath), 'utf8'))
const baseSupplementPath = 'content/campaigns/theInnsmouthConspiracy/story-source/base-supplements.json'
Object.assign(supplement.entries, JSON.parse(readFileSync(join(MOD, baseSupplementPath), 'utf8')).entries)
const read = (language, file) => JSON.parse(readFileSync(join(sourceRoot, language, 'theInnsmouthConspiracy', file), 'utf8'))
const locks = files.flatMap(file => ['en', 'zh'].map(language => sourceLock(`frontend/src/locales/${language}/theInnsmouthConspiracy/${file}`)))
const missing = [], translated = [], existing = []
function merge(en, zh, file, path = '') {
  if (typeof en === 'string') {
    const key = `${file}#${path}`, override = supplement.entries[key]
    const text = override ?? (typeof zh === 'string' && zh.trim() ? zh : en)
    const letters = text.replace(/<[^>]*>|\[[a-z_]+\]|\{[^}]+\}/gi, '')
    if (/[A-Za-z]{3}/.test(letters) && !/[\u3400-\u9fff]/.test(letters) && !text.startsWith('@:')) missing.push({ key, english: en, chinese: text })
    if (override != null) translated.push(key)
    else existing.push(key)
    const placeholders = value => [...String(value).matchAll(/\{[^}]*\}|\[(?:willpower|intellect|combat|agility|bless|curse|skull|cultist|tablet|elder_thing|auto_fail|per_investigator)\]/g)].map(m => m[0]).sort()
    if (override != null && json(placeholders(en)) !== json(placeholders(text))) throw new Error(`TIC translation placeholders differ: ${key}`)
    return text
  }
  if (Array.isArray(en)) return en.map((value, index) => merge(value, zh?.[index], file, path ? `${path}.${index}` : String(index)))
  if (en && typeof en === 'object') return Object.fromEntries(Object.entries(en).map(([key, value]) => [key, merge(value, zh?.[key], file, path ? `${path}.${key}` : key)]))
  return en
}
const story = { en: { scenarios: {} }, zh: { scenarios: {} } }
for (const file of files) {
  const en = read('en', file), zh = merge(en, read('zh', file), file)
  if (file === 'base.json') { story.en.base = en; story.zh.base = zh }
  else { const id = file.slice(10, -5); story.en.scenarios[id] = en; story.zh.scenarios[id] = zh }
}
const report = { schemaVersion: 1, generatedBy: 'node tools/import-tic-story.mjs --write', sourceKind: 'source-chinese-with-self-translated-supplements',
  officialChinese: false, sourceFiles: locks, supplements: [sourceLock(supplementPath, MOD), sourceLock(baseSupplementPath, MOD)],
  translated: translated.sort(), existing: existing.sort(), missing, gates: { completeChinese: missing.length === 0, allChapters: Object.keys(story.zh.scenarios).length === 8 } }
if (process.argv.includes('--missing')) { console.log(json(missing)); process.exit(0) }
if (missing.length) throw new Error(`TIC story has ${missing.length} untranslated strings; run --missing`)
const module = '// Generated by tools/import-tic-story.mjs; Chinese supplements are self-translated.\n'
  + `export const STORY_TEXT = Object.freeze(${JSON.stringify(story, null, 2)})\n`
  + `export const STORY_META = Object.freeze(${JSON.stringify({ sourceKind: report.sourceKind, officialChinese: false, sha256: sha(json(story)) })})\n`
for (const [path, contents] of [[output, module], ['audit/tic-story-acceptance.json', json(report)]]) {
  const absolute = join(MOD, path)
  if (process.argv.includes('--write')) writeFileSync(absolute, contents)
  else if (!existsSync(absolute) || readFileSync(absolute, 'utf8') !== contents) throw new Error(`${path} differs; review and --write`)
}
console.log(`TIC story: 8 chapters + base; ${translated.length} translated supplements; complete`)
