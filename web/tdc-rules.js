export function tdcCardRuleIds(card) {
  const text = [card.name, card.nameZh, card.text, card.textZh, card.backText, card.backTextZh,
    card.traits?.join(' ')].filter(Boolean).join('\n')
  return [...new Set(['tdcCampaign', ...(encounterRules[card.encounterCode] || []),
    ...Object.keys(cardPatterns).filter(id => cardPatterns[id].test(text))])]
}
